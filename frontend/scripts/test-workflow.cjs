const ts = require('typescript');
const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = ts.transpileModule(fs.readFileSync('lib/workflow.ts', 'utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS,esModuleInterop:true}}).outputText;
const context = { exports: {}, require: () => require('../lib/finishing-workflow.json'), Map };
vm.runInNewContext(source, context);
const { activityState, latestEvents, reference } = context.exports;
const event = (villa, activity, revision, status, progress) => ({villa_id:villa,activity_key:activity,revision,status,progress});
const history = [event('a','elle-001',1,'COMPLETED',100),event('a','elle-001',2,'REWORK_REQUIRED',0),event('a','elle-001',3,'IN_PROGRESS',20),event('a','elle-040',1,'IN_PROGRESS',30),event('b','elle-001',1,'COMPLETED',100)];
assert.equal(activityState(history,['a'],'elle-001').progress,20);
assert.equal(activityState(history,['a'],'elle-001').reworks,1);
assert.equal(activityState(history,['a'],'elle-040').status,'IN_PROGRESS');
assert.equal(activityState(history,['a','b'],'elle-001').progress,60);
assert.equal(activityState(history,['a','b','c'],'elle-001').recorded,2);
assert.equal(latestEvents([...history].reverse()).get('a/elle-001').revision,3);
assert.equal(activityState(history,['c'],'elle-001').recorded,0);
assert.equal(activityState([],[],'elle-001').status,'NOT_STARTED');
assert.equal(reference.activities.length,89);
assert.equal(reference.schedule.length,45);
assert.equal(reference.activities.reduce((sum,a)=>sum+(a.duration||0),0),526);
assert.ok(reference.schedule.find(r=>r.row===28).bands.length>1);
console.log('Workflow scenarios passed: parallel work, rework history, villa isolation, aggregates, source coverage.');
